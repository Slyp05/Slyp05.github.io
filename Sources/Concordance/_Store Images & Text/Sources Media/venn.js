// Generates the illustrations: each script a ring of its own ink, the three rings overlapping, and the value
// the ink region where all three agree. Usage: node venn.js (writes illustration.svg, illustration-card.svg and
// illustration-icon.svg).
"use strict";
const fs = require("fs");
const path = require("path");

// Ink on paper. Every image uses the same three inks in the same places: blue on top, ochre bottom left,
// crimson bottom right.
const inks = ["#2f5597", "#c98a1b", "#b23a48"];
const angles = [-90, 150, 30];
const chipColor = "#fbf8f2";
const inkColor = "#221d2b";

function f(x)
{
  return x.toFixed(1);
}

// A script file: a page with its top right corner folded, holding three code lines of different lengths.
function chip(cx, cy, size, stroke, color)
{
  const w = size * 0.84, h = size;
  const r = size * 0.14, fold = size * 0.3, line = size * 0.09;
  const left = cx - w / 2, top = cy - h / 2, right = left + w, bottom = top + h;
  const page = `M${f(left + r)} ${f(top)} H${f(right - fold)} L${f(right)} ${f(top + fold)} V${f(bottom - r)} Q${f(right)} ${f(bottom)} ${f(right - r)} ${f(bottom)}`
    + ` H${f(left + r)} Q${f(left)} ${f(bottom)} ${f(left)} ${f(bottom - r)} V${f(top + r)} Q${f(left)} ${f(top)} ${f(left + r)} ${f(top)} Z`;
  const corner = `M${f(right - fold)} ${f(top)} V${f(top + fold * 0.75)} Q${f(right - fold)} ${f(top + fold)} ${f(right - fold * 0.75)} ${f(top + fold)} H${f(right)}`;
  const lines = [0.46, 0.3, 0.38].map((lw, k) =>
    `<rect x="${f(left + w * 0.2)}" y="${f(cy + (k - 0.6) * h * 0.2 - line / 2 + h * 0.06)}" width="${f(size * lw)}" height="${f(line)}" rx="${f(line / 2)}" fill="${color}"/>`);
  return `<g filter="url(#shadow)">
    <path d="${page}" fill="${chipColor}" stroke="${color}" stroke-width="${stroke}" stroke-linejoin="round"/>
    <path d="${corner}" fill="none" stroke="${color}" stroke-width="${stroke}" stroke-linejoin="round"/>
    ${lines.join("\n    ")}
  </g>`;
}

function svg(o)
{
  const centres = angles.map(a => [o.cx + o.d * Math.cos(a * Math.PI / 180), o.cy + o.d * Math.sin(a * Math.PI / 180)]);
  const clips = centres.map((c, i) => `<clipPath id="ring${i}"><circle cx="${f(c[0])}" cy="${f(c[1])}" r="${o.r}"/></clipPath>`);
  // Light tints multiply where rings overlap, so each pair shows; the rings' own lines sit on top.
  const tints = centres.map((c, i) => `<circle cx="${f(c[0])}" cy="${f(c[1])}" r="${o.r}" fill="${inks[i]}" fill-opacity="${o.tint}" style="mix-blend-mode:multiply"/>`);
  const rings = centres.map((c, i) => `<circle cx="${f(c[0])}" cy="${f(c[1])}" r="${o.r}" fill="none" stroke="${inks[i]}" stroke-width="${o.stroke}"/>`);
  // The value: the region inside all three rings, in ink, under the rings' lines.
  const value = `<g clip-path="url(#ring0)"><g clip-path="url(#ring1)"><g clip-path="url(#ring2)"><rect x="${o.cx - o.r}" y="${o.cy - o.r}" width="${2 * o.r}" height="${2 * o.r}" fill="${inkColor}"/></g></g></g>`;
  // Each script's file sits in its own ring, in the part no other ring covers.
  const chips = (o.chip)
    ? "\n  " + centres.map((c, i) =>
    {
      const a = angles[i] * Math.PI / 180;
      return chip(c[0] + Math.cos(a) * o.r * 0.42, c[1] + Math.sin(a) * o.r * 0.42, o.chip, o.chipStroke, inks[i]);
    }).join("\n  ")
    : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${o.viewBox[2]}" height="${o.viewBox[3]}" viewBox="${o.viewBox.join(" ")}">
  <!-- Generated by venn.js; edit that file and re-run it instead of editing this one. -->
  <defs>
    ${clips.join("\n    ")}
    <filter id="shadow" x="-40%" y="-40%" width="180%" height="180%">
      <feDropShadow dx="0" dy="${f(o.r * 0.03)}" stdDeviation="${f(o.r * 0.03)}" flood-color="#5a4a30" flood-opacity="0.18"/>
    </filter>
  </defs>
  <g style="isolation:isolate">
    ${tints.join("\n    ")}
  </g>
  ${value}
  ${rings.join("\n  ")}${chips}
</svg>
`;
}

// Bounding box of the three rings with a margin, as an SVG viewBox.
function box(cx, cy, r, d, stroke, margin)
{
  const halfWidth = d * Math.cos(Math.PI / 6) + r + stroke / 2 + margin;
  const top = cy - d - r - stroke / 2 - margin, bottom = cy + d / 2 + r + stroke / 2 + margin;
  return [cx - halfWidth, top, 2 * halfWidth, bottom - top].map(v => Math.round(v));
}

function output(o)
{
  return Object.assign({ viewBox: box(o.cx, o.cy, o.r, o.d, o.stroke, o.margin) }, o);
}

const outputs = {
  // Cover and social; placed by each page at the size of its viewBox (or scaled).
  "illustration.svg": output({ cx: 0, cy: 0, r: 250, d: 142, stroke: 14, tint: 0.15, chip: 96, chipStroke: 4, margin: 20 }),
  // Card, drawn on its 840x560 canvas, without the script files: they blur at card size.
  "illustration-card.svg": output({ cx: 0, cy: 0, r: 96, d: 56, stroke: 10, tint: 0.16, chip: 0, chipStroke: 0, margin: 8 }),
  // Icon, drawn on its 320x320 canvas, without the script files.
  "illustration-icon.svg": output({ cx: 0, cy: 0, r: 88, d: 52, stroke: 16, tint: 0.18, chip: 0, chipStroke: 0, margin: 0 }),
};

for (const [file, o] of Object.entries(outputs))
{
  fs.writeFileSync(path.join(__dirname, file), svg(o));
  console.log(`Wrote ${file} (viewBox ${o.viewBox.join(" ")})`);
}
